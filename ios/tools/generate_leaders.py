#!/usr/bin/env python3
"""Embed the offline leader board-goal index; invoked by an authorized build."""
import json
from pathlib import Path
from update_leader_catalog import merge_fixed_profiles


def main():
    source = Path("ios/data/leader-orbs.json")
    raw = source.read_bytes()
    data = json.loads(raw)
    assert data["schema"] == 1 and data["region"] == "ja" and data["numbering"] == "encyclopedia"
    assert len(data["cards"]) > 14000 and len(data["skills"]) > 1000
    facts = json.loads(Path("ios/data/fixed-leader-skills.json").read_bytes())
    data = merge_fixed_profiles(data, facts)
    raw = (json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n").encode("utf-8")
    lines = ["// Generated by ios/tools/generate_leaders.py", "#pragma once",
             "static const unsigned char PHOrbLeaderData[] = {"]
    lines += [",".join(str(b) for b in raw[i:i+96]) + "," for i in range(0, len(raw), 96)]
    lines += ["};"]
    output = Path("ios/generated/PHOrbLeaderGenerated.h")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Embedded leader board goals: {len(raw)} bytes")


if __name__ == "__main__":
    main()
